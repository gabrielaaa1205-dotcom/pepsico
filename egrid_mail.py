def email_text(msg):
    parts=msg.walk() if msg.is_multipart() else [msg]
    text=[]
    for part in parts:
        if part.get_content_type() not in ('text/plain','text/html') or part.get_content_disposition()=='attachment':continue
        try:
            data=part.get_payload(decode=True) or b''
            charset=part.get_content_charset() or 'utf-8'
            value=data.decode(charset,errors='replace')
            if part.get_content_type()=='text/html':value=re.sub(r'<[^>]*>',' ',value)
            text.append(value[:14000])
        except Exception:pass
    return '\n'.join(text)[:18000]
def classify(mailbox,sender,recipient,subject,body):
    sender=sender.lower();recipient=recipient.lower()
    if mailbox=='sent':
        if 'compras@e-grid.app' in recipient.lower():return 'enviado'
        return None
    if 'noreply@e-grid.app' not in sender:return None
    t=(subject+' '+body[:5000]).lower()
    if re.search(r'\b(rechazad[ao]|rejected|no aprobada|observad[ao])\b',t):return 'rechazado'
    if re.search(r'\b(aprobada|aprobado|approved|aceptada|aceptado)\b',t):return 'aprobado'
    if re.search(r'\b(recibido|recibida|recepcionad[ao]|received|recepci[oó]n)\b',t):return 'recibido'
    return 'respuesta_sin_clasificar'
