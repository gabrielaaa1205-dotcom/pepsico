def number_candidates(s):
    t=str(s or '').upper()
    found=set()
    for p in re.findall(r'(?<![A-Z0-9])E001[\s\-_]*(\d{4,6})(?!\d)',t):
        found.add('E001-'+p)
    return found
def decode(s):
    try:return str(email.header.make_header(decode_header(s or '')))
    except:return str(s or '')
