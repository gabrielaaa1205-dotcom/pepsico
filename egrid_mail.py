@bp_mail.route('/api/egrid/sync',methods=['POST'])
def sync():
    authorized()
    from server import check_csrf
    check_csrf()
    password,user=imap_creds()
    if not password:return jsonify(error='Falta DREAMHOST_IMAP_PASSWORD en Render'),503
    host=os.getenv('DREAMHOST_IMAP_HOST','imap.dreamhost.com')
    updates=0;attachments=0;warnings=[];scan_info={}
    try:
        imap=imaplib.IMAP4_SSL(host,993,timeout=22)
        try:
            imap.login(user,password)
            ok,folders=imap.list()
            folders_text=[x.decode('utf-8',errors='replace') for x in (folders or [])]
            sent_candidates=['Sent','INBOX.Sent','Sent Messages','INBOX.Sent Messages','Enviados']
            sent=next((x for x in sent_candidates if any(('"'+x+'"').lower() in line.lower() or line.lower().endswith(' '+x.lower()) for line in folders_text)),None)
            if not sent:
                sent=next((line.rsplit('"',2)[1] for line in folders_text if ('\\Sent' in line or 'sent' in line.lower() or 'enviad' in line.lower()) and line.count('"')>=2),None)
            for alias,folder in [('received','INBOX'),('sent',sent)]:
                if not folder:
                    warnings.append('No se encontró carpeta Enviados');scan_info[alias]={'error':'carpeta_no_encontrada','available_folders':folders_text};continue
                if imap.select('"'+folder.replace('"','')+'"',readonly=True)[0]!='OK':
                    warnings.append('No se pudo abrir '+folder);scan_info[alias]={'error':'carpeta_no_accesible','folder':folder};continue
                since=(datetime.date.today()-datetime.timedelta(days=390)).strftime('%d-%b-%Y')
                typ,ids=imap.search(None,'SINCE',since)
                if typ!='OK':warnings.append('Búsqueda IMAP fallida: '+alias);continue
                uids=ids[0].split() if ids and ids[0] else []
                with database() as c:
                    ensure_tables(c)
                    row=c.execute('SELECT processed FROM egrid_scan_cursor WHERE folder=%s',(alias+'-full-search-v2',)).fetchone()
                    offset=row['processed'] if row else 0
                uids=list(reversed(uids))
                batch=uids[offset:offset+12]
                scan_info[alias]={'folder':folder,'matched':len(uids),'processed_before':offset,'this_batch':len(batch)}
                for mid in batch:
                    typ,parts=imap.fetch(mid,'(RFC822)')
                    if typ!='OK':continue
                    raw=next((p[1] for p in parts if isinstance(p,tuple) and isinstance(p[1],bytes)),None)
                    if not raw:continue
                    msg=email.message_from_bytes(raw)
                    sender=decode(msg.get('From'));recipient=decode(msg.get('To'));subject=decode(msg.get('Subject'))
                    body=email_text(msg)
                    state=classify(alias,sender,recipient,subject,body)
                    if not state:continue
                    candidates=number_candidates(subject+' '+body[:9000])
                    pdfs=[]
                    for p in msg.walk():
                        if p.get_content_type()!='application/pdf' and not decode(p.get_filename()).lower().endswith('.pdf'):continue
                        blob=p.get_payload(decode=True)
                        if blob and len(blob)<=8*1024*1024:
                            filename=decode(p.get_filename()) or 'factura.pdf'
                            pdfs.append((filename,blob))
                            candidates.update(number_candidates(filename))
                    if not candidates:continue
                    try:dt=parsedate_to_datetime(msg.get('Date'))
                    except:dt=None
                    with database() as c:
                        ensure_tables(c)
                        for inv in candidates:
                            n=c.execute("""INSERT INTO egrid_mail
                                (mailbox,uid,message_id,invoice,sender,recipient,subject,sent_at,evidence_type,excerpt)
                                VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)
                                ON CONFLICT DO NOTHING RETURNING id""",
                                (alias,mid.decode(),msg.get('Message-ID'),inv,sender[:350],recipient[:600],subject[:900],dt,state,body[:1500])).fetchone()
                            updates+=bool(n)
                            for filename,blob in pdfs:
                                # Never attach a mismatched PDF to unrelated invoices.
                                mentioned=number_candidates(filename)
                                if mentioned and inv not in mentioned:continue
                                result=c.execute("""INSERT INTO egrid_pdf(invoice,mailbox,uid,filename,content)
                                    VALUES (%s,%s,%s,%s,%s) ON CONFLICT DO NOTHING RETURNING id""",
                                    (inv,alias,mid.decode(),filename[:240],blob)).fetchone()
                                attachments+=bool(result)
                with database() as c:
                    c.execute('INSERT INTO egrid_scan_cursor(folder,processed) VALUES (%s,%s) ON CONFLICT(folder) DO UPDATE SET processed=EXCLUDED.processed',(alias+'-full-search-v2',offset+len(batch)))
        finally:
            try:imap.logout()
            except Exception:pass
    except Exception as e:
        return jsonify(error='Error de conexión IMAP. Comprueba usuario, contraseña y acceso de red.',kind=type(e).__name__),502
    return jsonify(ok=True,new_events=updates,new_pdfs=attachments,warnings=warnings,scan=scan_info,complete=all(v.get('processed_before',0)+v.get('this_batch',0)>=v.get('matched',0) for v in scan_info.values() if 'matched' in v),note='Importación por lotes; las carpetas sin coincidencias no producen PDF.')
@bp_mail.route('/api/egrid/invoices')
def invoices():
    authorized()
    with database() as c:
        ensure_tables(c)
        ev=c.execute("""SELECT invoice,evidence_type,sent_at,subject,sender,message_id,id
                         FROM egrid_mail ORDER BY sent_at DESC NULLS LAST,id DESC LIMIT 3000""").fetchall()
        docs=c.execute("SELECT id,invoice,filename,created_at FROM egrid_pdf ORDER BY id DESC LIMIT 500").fetchall()
    groups={}
    for r in ev:
        k=r['invoice'];d=groups.setdefault(k,{'events':{},'pdfs':[]})
        t=r['evidence_type']
        if t not in d['events']:
            d['events'][t]={'date':r['sent_at'].isoformat() if r['sent_at'] else None,
                            'subject':r['subject'],'sender':r['sender'],'evidence_id':r['id']}
    for r in docs:
        groups.setdefault(r['invoice'],{'events':{},'pdfs':[]})['pdfs'].append({'id':r['id'],'filename':r['filename']})
    return jsonify(invoices=groups)
@bp_mail.route('/api/egrid/pdf/<int:pdf_id>')
def pdf(pdf_id):
    authorized()
    with database() as c:
        ensure_tables(c)
        record=c.execute('SELECT filename,content FROM egrid_pdf WHERE id=%s',(pdf_id,)).fetchone()
    if not record:abort(404)
    filename=re.sub(r'[^\w. -]','_',record['filename'] or 'factura.pdf')
    response=send_file(io.BytesIO(bytes(record['content'])),mimetype='application/pdf',download_name=filename,as_attachment=False)
    response.headers['Cache-Control']='private, no-store'
    return response
